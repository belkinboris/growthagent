"""
Какой вопрос задать людям (задача R14).

Зачем модуль появился. R12 научился видеть застой, но заканчивал советом
владельцу: «сходите и поговорите с пятью незаплатившими». Владелец
справедливо возразил: платформа делается ради того, чтобы продукт
развивался сам, а не чтобы фаундер ходил с блокнотом. Причину неоплаты
знают только сами люди — значит, спрашивать должен продукт, электронно, а
платформа обязана лишь правильно сформулировать вопрос и собрать ответы.

Здесь — только формулировка: какой вопрос, кому и почему. Доставка живёт
в endpoint'ах (продукт забирает вопрос сам, см. `UserQuestion`), потому
что у аналитика нет и не должно быть доступа к людям.

Правила, из которых выросли формулировки (не украшения, а суть):

1. Вопрос открытый и про прошлое, не про будущее. «Что должно было
   случиться, чтобы вы заплатили?» вместо «Вы бы заплатили, если…».
   Гипотетический вопрос собирает вежливые фантазии, вопрос про уже
   прожитый опыт — факты. Это самая частая ошибка в опросах основателей.
2. Один вопрос за раз. Анкета из пяти пунктов даёт отказ, а не ответы.
3. Не предлагаем варианты ответа. Список вариантов возвращает наши же
   гипотезы, а нам нужны слова людей — ровно то, чего нет ни в одной
   метрике.
4. Спрашиваем тех, кто СТОЛКНУЛСЯ с проблемой, а не всех подряд: человека,
   который дошёл до цен и не заплатил, а не всю базу.

LLM здесь не участвует: набор вопросов конечен и выверен, генерировать их
на лету значило бы каждый раз спрашивать людей чуть-чуть иначе и не иметь
возможности сравнить ответы между собой.
"""
from __future__ import annotations

from dataclasses import dataclass
from typing import Optional

# Сколько ответов считаем достаточным, чтобы перестать спрашивать. Пять --
# не статистика, и не должно ею притворяться: это порог, на котором у
# качественных ответов обычно начинают повторяться формулировки. Вывод из
# них — направление, а не измерение (так и пишем владельцу).
DEFAULT_TARGET_ANSWERS = 5


@dataclass(frozen=True)
class QuestionPlan:
    """Что спросить, у кого и зачем."""

    segment: str        # stuck_at из user-journeys
    question: str       # текст, который увидит человек
    reason: str         # зачем спрашиваем — объяснение владельцу
    target_answers: int = DEFAULT_TARGET_ANSWERS


# Вопрос на каждый диагноз застоя (см. app/course.py). Ключ -- то, что
# сломано, значение -- кого и о чём спрашивать.
PLANS: dict[str, QuestionPlan] = {
    "no_money": QuestionPlan(
        segment="pricing",
        question=(
            "Вы посмотрели тарифы, но не оформили подписку. Подскажите, "
            "пожалуйста, что вас остановило? Ответьте одной фразой — это "
            "очень поможет нам сделать сервис лучше."
        ),
        reason=(
            "Люди доходят до цен и не платят. Почему — не видно ни в одной "
            "метрике: это знают только они сами."
        ),
    ),
    "no_demand": QuestionPlan(
        segment="first_post",
        question=(
            "Вы попробовали сгенерировать пост и не вернулись. Скажите, "
            "пожалуйста, чего вам не хватило? Одной фразы достаточно."
        ),
        reason=(
            "Люди пробуют продукт и уходят. Нужны их слова о том, что "
            "оказалось не так, — по числам эту причину не восстановить."
        ),
    ),
    "flat": QuestionPlan(
        segment="pricing",
        question=(
            "Вы пользуетесь сервисом, но не оформили подписку. Что должно "
            "было бы измениться, чтобы она стала для вас полезной?"
        ),
        reason=(
            "Продукт не растёт, при этом явного обрыва в воронке нет. "
            "Значит, вопрос не в шагах, а в ценности — её называют люди."
        ),
    ),
    "paid": QuestionPlan(
        segment="paid",
        question=(
            "Спасибо за подписку! Один короткий вопрос: за что именно вы "
            "платите — что стало главной причиной?"
        ),
        reason=(
            "Заплативших мало, тем ценнее каждый: их формулировка ценности "
            "-- готовый текст для лендинга и для объявлений."
        ),
    ),
}


def plan_for_course(course: dict | None) -> Optional[QuestionPlan]:
    """
    Подбирает вопрос по выводу о курсе продукта (`app.course.Course`).

    Возвращает None, если спрашивать не о чем: продукт растёт или данных
    для вывода пока мало. Спрашивать людей «просто так» нельзя — каждый
    вопрос тратит их терпение, и задавать его без причины значит
    расходовать доверие впустую.
    """
    if not course or not course.get("ok") or not course.get("stalled"):
        return None

    headline = (course.get("headline") or "").lower()
    if "деньги не появляются" in headline:
        return PLANS["no_money"]
    if "новых людей почти нет" in headline:
        return PLANS["no_demand"]
    return PLANS["flat"]


def summarize_answers(answers: list) -> dict:
    """
    Сводка ответов для владельца. Никакой автоматической «кластеризации»:
    на пяти ответах она превратила бы живые формулировки в три
    обезличенных ярлыка, а ценность именно в словах. Поэтому — сами
    ответы плюс честная оценка, можно ли на них опираться.
    """
    texts = [a for a in (answers or []) if (a or "").strip()]
    count = len(texts)
    if count == 0:
        note = "Ответов пока нет."
    elif count < 3:
        note = (
            f"{count} — этого мало даже для направления: "
            "прочитайте, но выводов пока не делайте."
        )
    elif count < DEFAULT_TARGET_ANSWERS:
        note = (
            f"{count} — уже видно направление. Если одно и то же повторяется "
            "дважды, это не совпадение."
        )
    else:
        note = (
            f"{count} — достаточно, чтобы увидеть повторяющуюся причину. "
            "Это направление, а не измерение: проценты по ним не считаем."
        )
    return {"count": count, "answers": texts, "note": note}
